package gamedata

import (
	"fmt"
	"log"
	"strings"
)

// uiKeys are the site's own interface strings the game shows (eo.json).
var uiKeys = []string{"exercise.choose_answer", "exercise.what_means", "exercise.dont_know", "exercise.send",
	"home.start_cta", "home.continue_cta", "exercise.series_next_fallback", "exercise.series_prev_fallback",
	"exercise.answer_placeholder", "exercise.vocab_mode_type", "exercise.vocab_prompt", "exercise.phrase_prompt",
	"exercise.loading"}

// FallbackSeries is the part of the course built into the game, for when the
// site can't be reached and nothing is cached yet.
var FallbackSeries = []string{"zagr-metodo"}

// gmlRaw writes s as a GML string literal: tabs and line breaks may stand in
// it as they are; a double quote is spliced in from a single-quoted one.
func gmlRaw(s string) string {
	parts := strings.Split(s, `"`)
	for i, p := range parts {
		parts[i] = `"` + p + `"`
	}
	return strings.Join(parts, `+'"'+`)
}

// GML is the game's data script (scripts/course_data.gml): the interface
// strings, and the fallback — the map of FallbackSeries and their places'
// lessons, in the same text the site serves (meanings in English).
func GML(c *Course, ui map[string]string) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...); b.WriteByte('\n') }
	b.WriteString("// Code generated by cmd/export-game from the site's seed data; DO NOT EDIT.\n")
	b.WriteString("// The game loads the course from the site (/ludo-api/); this is only its fallback.\n")
	for _, k := range uiKeys {
		if ui[k] == "" {
			log.Fatalf("eo.json has no %s", k)
		}
		w("global.t_%s = %s", k[strings.LastIndex(k, ".")+1:], gmlStr(ui[k])) // exercise.send → global.t_send
	}
	part := &Course{Version: "fallback-" + c.Version, Langs: []string{"en"}}
	keep := map[string]bool{}
	for _, s := range FallbackSeries {
		keep[s] = true
	}
	for _, s := range c.Series {
		if keep[s.Slug] {
			part.Series = append(part.Series, s)
			part.Places = append(part.Places, s.Places...)
		}
	}
	if len(part.Places) == 0 {
		log.Fatalf("the built-in part (%v) has no places", FallbackSeries)
	}
	var mb strings.Builder
	WriteCourse(&mb, part)
	w("global.fb_course = %s", gmlRaw(mb.String()))
	w("global.fb_n = %d", len(part.Places))
	for i, p := range part.Places {
		var lb strings.Builder
		WriteLesson(&lb, part, p, "en")
		w("global.fb_slug[%d] = %s", i, gmlRaw(p.Slug))
		w("global.fb_text[%d] = %s", i, gmlRaw(lb.String()))
	}
	return b.String()
}
