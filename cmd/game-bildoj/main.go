// Command game-bildoj writes the pictures Vortludo can offer as a hint: the
// site's word pictures (internal/bildoj, OpenMoji, CC BY-SA 4.0) of every
// five-letter word, rendered from static/bildoj/ at the size the game draws
// them (GameViber has no SVG and loads no pictures at run time), as one
// sprite, game/sprites/spr_bildo, and game/scripts/bildo_frame.gml, which
// finds a picture's frame by the name /ludo-api/vortoj gives it. Needs
// rsvg-convert and ImageMagick's magick. Run it again after changing
// vortbildoj.json:
//
//	go run ./cmd/game-bildoj
package main

import (
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/LaPingvino/esperanto-kurso-gae/internal/bildoj"
	"github.com/LaPingvino/esperanto-kurso-gae/internal/gamedata"
)

const size = 96

func main() {
	spr := filepath.Join("game", "sprites", "spr_bildo")
	tmp, err := os.MkdirTemp("", "game-bildoj")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(tmp)
	var pngs, keys []string
	seen := map[string]bool{}
	for _, p := range bildoj.All() {
		key := gamedata.PictureKey(p.Word)
		if !gamedata.IsFive(p.Word) || key == "" || seen[key] {
			continue
		}
		seen[key] = true
		out := filepath.Join(tmp, fmt.Sprintf("%03d.png", len(pngs)))
		run("rsvg-convert", "-w", fmt.Sprint(size), "-h", fmt.Sprint(size), "-o", out, filepath.Join("static", "bildoj", p.File))
		pngs = append(pngs, out)
		keys = append(keys, key)
	}
	if err := os.MkdirAll(spr, 0o755); err != nil {
		log.Fatal(err)
	}
	run("magick", append(append([]string{}, pngs...), "+append", "-strip", "-define", "png:exclude-chunk=time,tEXt,zTXt,iTXt", filepath.Join(spr, "strip.png"))...)
	toml := fmt.Sprintf("frames = %d\nframe_w = %d\nframe_h = %d\norigin = [0, 0]\nbbox_lrbt = [0, %d, 0, %d]\nprecise = false\ntransparent = false\n", len(keys), size, size, size-1, size-1)
	write(filepath.Join(spr, "sprite.toml"), toml)
	var b strings.Builder
	b.WriteString("// Code generated by cmd/game-bildoj from internal/bildoj; DO NOT EDIT.\n")
	b.WriteString("// bildo_frame(key): the frame of spr_bildo with that word picture, -1 for none.\n")
	for i, k := range keys {
		fmt.Fprintf(&b, "if (argument0 == %q) return %d;\n", k, i)
	}
	b.WriteString("return -1;\n")
	write(filepath.Join("game", "scripts", "bildo_frame.gml"), b.String())
	log.Printf("%d pictures", len(keys))
}

func run(name string, args ...string) {
	if out, err := exec.Command(name, args...).CombinedOutput(); err != nil {
		log.Fatalf("%s: %v\n%s", name, err, out)
	}
}

func write(path, s string) {
	if err := os.WriteFile(path, []byte(s), 0o644); err != nil {
		log.Fatal(err)
	}
}
